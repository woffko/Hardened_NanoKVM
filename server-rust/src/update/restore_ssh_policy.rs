//! Restore-only authority inventory for pinned OpenSSH 10.6p1 directives.
//! Scalar means no server-side file/socket/command authority, not syntax PASS.

#[derive(Clone, Copy)]
pub(super) enum Rule {
    Scalar,
    Include,
    HostKey,
    HostCertificate,
    AuthorizedKeys,
    Data,
    Agent,
    Provider,
    Pid,
    Session,
    Auth,
    Xauth,
    Subsystem,
    Force,
    DisabledHook,
    DisabledEnvironment,
    NoChroot,
    NoPam,
    Match,
}

pub(super) fn rule(name: &[u8]) -> Option<Rule> {
    for (names, rule) in RULES {
        if names
            .iter()
            .any(|known| name.eq_ignore_ascii_case(known.as_bytes()))
        {
            return Some(*rule);
        }
    }
    None
}

