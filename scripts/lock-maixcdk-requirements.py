#!/usr/bin/env python3
"""Print a hash-pinned requirements file for the Docker SDK image.

Reads ``name==version`` lines on stdin: ``pip freeze`` of the MaixCDK virtual
environment that the native builds use. For each, it lists the SHA-256 of the
PyPI wheels that fit CPython 3.12 on x86_64 glibc Linux (the Docker build
platform), or of the source distribution when no wheel fits. Review the
output before it replaces docker/maixcdk-requirements.lock.
"""

import json
import re
import sys
import urllib.request

REQUIREMENT = re.compile(r"^([A-Za-z0-9._-]+)==([A-Za-z0-9.+!_-]+)$")


def fits(filename):
    if filename.endswith("-none-any.whl"):
        return True
    return (
        filename.endswith(".whl")
        and ("-cp312-" in filename or "-abi3-" in filename)
        and "manylinux" in filename
        and "x86_64" in filename
    )


def hashes(name, version):
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as reply:
        files = json.load(reply)["urls"]
    wheels = [f["digests"]["sha256"] for f in files if fits(f["filename"])]
    if wheels:
        return sorted(wheels)
    sources = [f["digests"]["sha256"] for f in files if f["packagetype"] == "sdist"]
    if not sources:
        raise SystemExit(f"{name}=={version}: no fitting wheel or source distribution")
    return sorted(sources)


def main():
    print("# Generated by scripts/lock-maixcdk-requirements.py from the MaixCDK")
    print("# environment of the native builds; install with --require-hashes --no-deps.")
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        match = REQUIREMENT.match(line)
        if not match:
            raise SystemExit(f"not a pinned requirement: {line}")
        name, version = match.groups()
        digests = hashes(name, version)
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{digest}" for digest in digests))


if __name__ == "__main__":
    main()
